CREATE TABLE QUERY_PILOT_INVESTIGATIONS (
    INVESTIGATION_ID   VARCHAR2(50) PRIMARY KEY,
    TITLE              VARCHAR2(200) NOT NULL,
    DESCRIPTION        VARCHAR2(4000),
    CATEGORY           VARCHAR2(50) NOT NULL,
    SEVERITY           VARCHAR2(20) NOT NULL,
    STATUS             VARCHAR2(30) DEFAULT 'OPEN' NOT NULL,
    INITIAL_HYPOTHESIS VARCHAR2(4000),
    BASELINE_SQL       CLOB,
    CANDIDATE_SQL      CLOB,
    ROOT_CAUSE         VARCHAR2(4000),
    PROPOSED_FIX       VARCHAR2(4000),
    VERIFICATION_NOTES VARCHAR2(4000),
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVED_AT        TIMESTAMP
);

CREATE TABLE QUERY_PILOT_AUDIT_LOG (
    LOG_ID             NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVESTIGATION_ID   VARCHAR2(50) REFERENCES QUERY_PILOT_INVESTIGATIONS(INVESTIGATION_ID),
    EVENT_TYPE         VARCHAR2(50) NOT NULL,
    EVENT_DESCRIPTION  VARCHAR2(1000) NOT NULL,
    EVENT_TIMESTAMP    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    USER_IDENTITY      VARCHAR2(100) DEFAULT USER NOT NULL
);

CREATE INDEX IDX_AUDIT_INV ON QUERY_PILOT_AUDIT_LOG(INVESTIGATION_ID);
