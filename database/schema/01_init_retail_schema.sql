-- Drop existing tables in reverse dependency order if recreating
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'QUERY_PILOT_AUDIT_LOG', 'QUERY_PILOT_COMPARISONS', 'QUERY_PILOT_EXECUTIONS',
        'QUERY_PILOT_INVESTIGATIONS', 'SUPPORT_TICKETS', 'SHIPMENTS', 'PAYMENTS',
        'ORDER_ITEMS', 'ORDERS', 'CUSTOMERS', 'PRODUCTS', 'CATEGORIES'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- 1. Product Categories
CREATE TABLE CATEGORIES (
    CATEGORY_ID     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME   VARCHAR2(100) NOT NULL,
    SLUG            VARCHAR2(100) NOT NULL CONSTRAINT UQ_CAT_SLUG UNIQUE,
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT CK_CAT_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

COMMENT ON TABLE CATEGORIES IS 'Hierarchical taxonomy for product catalog classifications.';

-- 2. Products
CREATE TABLE PRODUCTS (
    PRODUCT_ID      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_ID     NUMBER(10) NOT NULL CONSTRAINT FK_PROD_CAT REFERENCES CATEGORIES(CATEGORY_ID),
    SKU             VARCHAR2(50) NOT NULL CONSTRAINT UQ_PROD_SKU UNIQUE,
    PRODUCT_NAME    VARCHAR2(200) NOT NULL,
    UNIT_PRICE      NUMBER(10, 2) NOT NULL CONSTRAINT CK_PROD_PRICE CHECK (UNIT_PRICE >= 0),
    COST_PRICE      NUMBER(10, 2) NOT NULL CONSTRAINT CK_PROD_COST CHECK (COST_PRICE >= 0),
    STOCK_QUANTITY  NUMBER(10) DEFAULT 0 NOT NULL CONSTRAINT CK_PROD_QTY CHECK (STOCK_QUANTITY >= 0),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL CONSTRAINT CK_PROD_STATUS CHECK (STATUS IN ('ACTIVE', 'DISCONTINUED', 'OUT_OF_STOCK')),
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_PROD_CAT ON PRODUCTS(CATEGORY_ID);
CREATE INDEX IDX_PROD_STATUS ON PRODUCTS(STATUS);
COMMENT ON TABLE PRODUCTS IS 'Retail merchandise catalog with pricing and stock levels.';

-- 3. Customers
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME      VARCHAR2(60) NOT NULL,
    LAST_NAME       VARCHAR2(60) NOT NULL,
    EMAIL           VARCHAR2(120) NOT NULL CONSTRAINT UQ_CUST_EMAIL UNIQUE,
    PHONE           VARCHAR2(30),
    LOYALTY_TIER    VARCHAR2(20) DEFAULT 'STANDARD' NOT NULL CONSTRAINT CK_CUST_TIER CHECK (LOYALTY_TIER IN ('STANDARD', 'SILVER', 'GOLD', 'PLATINUM')),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL CONSTRAINT CK_CUST_STATUS CHECK (STATUS IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_CUST_TIER ON CUSTOMERS(LOYALTY_TIER);
COMMENT ON TABLE CUSTOMERS IS 'Customer accounts with loyalty tiering and contact details.';

-- 4. Orders
CREATE TABLE ORDERS (
    ORDER_ID        NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID     NUMBER(10) NOT NULL CONSTRAINT FK_ORDERS_CUST REFERENCES CUSTOMERS(CUSTOMER_ID),
    ORDER_DATE      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    TOTAL_AMOUNT    NUMBER(12, 2) NOT NULL CONSTRAINT CK_ORD_TOTAL CHECK (TOTAL_AMOUNT >= 0),
    STATUS          VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL CONSTRAINT CK_ORD_STATUS CHECK (STATUS IN ('PENDING', 'PROCESSING', 'SHIPPED', 'COMPLETED', 'CANCELLED')),
    PAYMENT_STATUS  VARCHAR2(20) DEFAULT 'PAID' NOT NULL CONSTRAINT CK_ORD_PAY CHECK (PAYMENT_STATUS IN ('PENDING', 'PAID', 'REFUNDED', 'FAILED')),
    SHIPPING_STATUS VARCHAR2(20) DEFAULT 'DELIVERED' NOT NULL CONSTRAINT CK_ORD_SHIP CHECK (SHIPPING_STATUS IN ('PENDING', 'IN_TRANSIT', 'DELIVERED', 'RETURNED'))
);

CREATE INDEX IDX_ORDERS_CUST ON ORDERS(CUSTOMER_ID);
CREATE INDEX IDX_ORDERS_DATE ON ORDERS(ORDER_DATE);
CREATE INDEX IDX_ORDERS_STATUS ON ORDERS(STATUS);
COMMENT ON TABLE ORDERS IS 'Customer purchase transactions and fulfillment status.';

-- 5. Order Line Items
CREATE TABLE ORDER_ITEMS (
    ITEM_ID         NUMBER(14) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID        NUMBER(12) NOT NULL CONSTRAINT FK_ITEMS_ORD REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE,
    PRODUCT_ID      NUMBER(10) NOT NULL CONSTRAINT FK_ITEMS_PROD REFERENCES PRODUCTS(PRODUCT_ID),
    QUANTITY        NUMBER(6) NOT NULL CONSTRAINT CK_ITEM_QTY CHECK (QUANTITY > 0),
    UNIT_PRICE      NUMBER(10, 2) NOT NULL,
    DISCOUNT        NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    LINE_TOTAL      NUMBER(12, 2) NOT NULL
);

CREATE INDEX IDX_ITEMS_ORD ON ORDER_ITEMS(ORDER_ID);
CREATE INDEX IDX_ITEMS_PROD ON ORDER_ITEMS(PRODUCT_ID);
COMMENT ON TABLE ORDER_ITEMS IS 'Line item details for individual product units per order.';

-- 6. Payments
CREATE TABLE PAYMENTS (
    PAYMENT_ID       NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID         NUMBER(12) NOT NULL CONSTRAINT FK_PAY_ORD REFERENCES ORDERS(ORDER_ID),
    PAYMENT_METHOD   VARCHAR2(30) NOT NULL CONSTRAINT CK_PAY_METHOD CHECK (PAYMENT_METHOD IN ('CREDIT_CARD', 'PAYPAL', 'WIRE_TRANSFER', 'APPLE_PAY')),
    AMOUNT           NUMBER(12, 2) NOT NULL,
    STATUS           VARCHAR2(20) DEFAULT 'SETTLED' NOT NULL CONSTRAINT CK_PAY_STATUS CHECK (STATUS IN ('SETTLED', 'PENDING', 'FAILED', 'REFUNDED')),
    TRANSACTION_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_PAY_ORD ON PAYMENTS(ORDER_ID);
COMMENT ON TABLE PAYMENTS IS 'Financial payment transactions matched against customer orders.';

-- 7. Shipments
CREATE TABLE SHIPMENTS (
    SHIPMENT_ID      NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID         NUMBER(12) NOT NULL CONSTRAINT FK_SHIP_ORD REFERENCES ORDERS(ORDER_ID),
    CARRIER          VARCHAR2(50) NOT NULL,
    TRACKING_NUMBER  VARCHAR2(80) CONSTRAINT UQ_SHIP_TRACK UNIQUE,
    SHIPPED_AT       TIMESTAMP,
    DELIVERED_AT     TIMESTAMP,
    STATUS           VARCHAR2(20) DEFAULT 'DELIVERED' NOT NULL CONSTRAINT CK_SHIP_STATUS CHECK (STATUS IN ('PENDING', 'IN_TRANSIT', 'DELIVERED', 'RETURNED'))
);

CREATE INDEX IDX_SHIP_ORD ON SHIPMENTS(ORDER_ID);
COMMENT ON TABLE SHIPMENTS IS 'Logistics carrier tracking and delivery timeline events.';

-- 8. Customer Support Tickets
CREATE TABLE SUPPORT_TICKETS (
    TICKET_ID        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID      NUMBER(10) NOT NULL CONSTRAINT FK_TICKET_CUST REFERENCES CUSTOMERS(CUSTOMER_ID),
    ORDER_ID         NUMBER(12) CONSTRAINT FK_TICKET_ORD REFERENCES ORDERS(ORDER_ID),
    SUBJECT          VARCHAR2(200) NOT NULL,
    STATUS           VARCHAR2(20) DEFAULT 'CLOSED' NOT NULL CONSTRAINT CK_TICKET_STATUS CHECK (STATUS IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    PRIORITY         VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL CONSTRAINT CK_TICKET_PRIORITY CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_TICKET_CUST ON SUPPORT_TICKETS(CUSTOMER_ID);
CREATE INDEX IDX_TICKET_STATUS ON SUPPORT_TICKETS(STATUS);
COMMENT ON TABLE SUPPORT_TICKETS IS 'Customer service tickets linked to customers and specific orders.';

